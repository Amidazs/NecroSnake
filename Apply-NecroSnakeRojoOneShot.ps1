        "    if should_raise() then",
        "        ArmyService.AddUnit(killer_owner, unit_type, (ArmyService.GetArmy(killer_owner).Kind == ""Player"") and ""Player"" or ""Named"")",
        "        return true",
        "    end",
        "    return false",
        "end",
        "",
        "local function destroy_part(part)",
        "    if part and part.Parent then",
        "        part:Destroy()",
        "    end",
        "end",
        "",
        "local function resolve_death(killer, victim)",
        "    local killer_owner = killer:GetAttribute(""OwnerId"")",
        "    local victim_owner = victim:GetAttribute(""OwnerId"")",
        "    local victim_type = victim:GetAttribute(""Type"") or victim.Name or ""Skeleton""",
        "",
        "    local victim_kind = victim:GetAttribute(""Kind"")",
        "    local victim_leader_kind = victim:GetAttribute(""LeaderKind"")",
        "",
        "    -- Named leader death: guaranteed boss raise for killer (if raiser)",
        "    if victim_kind == ""Leader"" and victim_leader_kind == ""NamedNPC"" then",
        "        if GameConfig.Raising.NamedLeaderKillGuaranteedBossRaise then",
        "            local ok = try_raise_unit(killer_owner, GameConfig.Raising.BossRaiseType, true)",
        "            dbg(""Named leader killed. Guaranteed boss raise=%s for killer=%s"", tostring(ok), tostring(killer_owner))",
        "        end",
        "        local army = ArmyService.GetArmy(victim_owner)",
        "        if army then",
        "            ArmyService.ClearUnits(victim_owner)",
        "            if army.Leader and army.Leader.Parent then",
        "                army.Leader:Destroy()",
        "            end",
        "            -- leave expiry cleanup to ArmyService.RemoveExpired; hard-remove now",
        "            ArmyService.GetAllArmies()[victim_owner] = nil",
        "        end",
        "        return",
        "    end",
        "",
        "    -- Wandering units do not get raised by wanderers (they cannot raise),",
        "    -- but can be raised by player/named killers.",
        "    local raised = false",
        "    if victim_kind == ""Unit"" then",
        "        raised = try_raise_unit(killer_owner, victim_type, false)",
        "    end",
        "",
        "    if raised then",
        "        dbg(""Raised unit: killer=%s type=%s"", tostring(killer_owner), tostring(victim_type))",
        "        destroy_part(victim)",
        "    else",
        "        destroy_part(victim)",
        "    end",
        "end",
        "",
        "local function apply_damage(attacker, target)",
        "    local dmg = get_damage(attacker)",
        "    local hp = target:GetAttribute(""HP"")",
        "    local max_hp = target:GetAttribute(""MaxHP"")",
        "    if typeof(hp) ~= ""number"" or typeof(max_hp) ~= ""number"" then",
        "        return",
        "    end",
        "    if hp <= 0 then",
        "        return",
        "    end",
        "",
        "    local new_hp = hp - dmg",
        "    target:SetAttribute(""HP"", new_hp)",
        "    if new_hp <= 0 then",
        "        resolve_death(attacker, target)",
        "    end",
        "end",
        "",
        "local function collect_combat_parts()",
        "    local list = {}",
        "    for _, army in pairs(ArmyService.GetAllArmies()) do",
        "        if army.Leader and army.Leader.Parent then",
        "            table.insert(list, army.Leader)",
        "        end",
        "        for _, u in ipairs(army.Units) do",
        "            if u.Part and u.Part.Parent then",
        "                table.insert(list, u.Part)",
        "            end",
        "        end",
        "    end",
        "    for _, group in pairs(ArmyService.GetRoamingGroups()) do",
        "        for _, u in ipairs(group.Units) do",
        "            if u.Part and u.Part.Parent then",
        "                table.insert(list, u.Part)",
        "            end",
        "        end",
        "    end",
        "    return list",
        "end",
        "",
        "function CombatService.Start()",
        "    dbg(""Ready."")",
        "    task.spawn(function()",
        "        while true do",
        "            CombatService.Tick()",
        "            task.wait(GameConfig.Combat.AttackCooldownSeconds)",
        "        end",
        "    end)",
        "end",
        "",
        "function CombatService.Tick()",
        "    local parts = collect_combat_parts()",
        "    if #parts <= 1 then",
        "        return",
        "    end",
        "",
        "    for i = 1, #parts do",
        "        local a = parts[i]",
        "        if a and a.Parent and is_alive(a) then",
        "            local owner_a = a:GetAttribute(""OwnerId"")",
        "            local best = nil",
        "            local best_d = GameConfig.Combat.AttackRange",
        "",
        "            for j = 1, #parts do",
        "                if j ~= i then",
        "                    local b = parts[j]",
        "                    if b and b.Parent and is_alive(b) then",
        "                        local owner_b = b:GetAttribute(""OwnerId"")",
        "                        if owner_b ~= nil and owner_a ~= nil and owner_b ~= owner_a then",
        "                            local d = (a.Position - b.Position).Magnitude",
        "                            if d < best_d then",
        "                                best_d = d",
        "                                best = b",
        "                            end",
        "                        end",
        "                    end",
        "                end",
        "            end",
        "",
        "            if best then",
        "                apply_damage(a, best)",
        "            end",
        "        end",
        "    end",
        "end",
        "",
        "return CombatService"
    )
    Write-TextFileUtf8NoBom -Path (Join-Path $services_dir "CombatService.lua") -Lines $combat_service

    # -----------------------------
    # Main.server.lua
    # -----------------------------
    $main_server = @(
        "local Players = game:GetService(""Players"")",
        "",
        "print(""[Server] Booting NecroSnake"")",
        "",
        "local GameConfig = require(script.Parent.Services.GameConfig)",
        "local WorldService = require(script.Parent.Services.WorldService)",
        "local BoundaryService = require(script.Parent.Services.BoundaryService)",
        "local ModelLibraryService = require(script.Parent.Services.ModelLibraryService)",
        "local ArmyService = require(script.Parent.Services.ArmyService)",
        "local SpawnService = require(script.Parent.Services.SpawnService)",
        "local AIStrategyService = require(script.Parent.Services.AIStrategyService)",
        "local CombatService = require(script.Parent.Services.CombatService)",
        "",
        "local world = WorldService.EnsureWorld(GameConfig)",
        "BoundaryService.BuildWalls(GameConfig, world.Arena)",
        "ModelLibraryService.Sanitize()",
        "",
        "ArmyService.Start(world.Units, world.Leaders)",
        "SpawnService.Start()",
        "AIStrategyService.Start()",
        "CombatService.Start()",
        "",
        "local function setup_player(player)",
        "    player.CharacterAdded:Connect(function(char)",
        "        local hrp = char:WaitForChild(""HumanoidRootPart"")",
        "        hrp:SetAttribute(""OwnerId"", player.UserId)",
        "        hrp:SetAttribute(""Kind"", ""Leader"")",
        "        hrp:SetAttribute(""LeaderKind"", ""Player"")",
        "        hrp:SetAttribute(""DisplayName"", player.Name)",
        "        hrp:SetAttribute(""HP"", GameConfig.Player.BaseHealth)",
        "        hrp:SetAttribute(""MaxHP"", GameConfig.Player.BaseHealth)",
        "        hrp:SetAttribute(""Damage"", GameConfig.Player.BaseDamage)",
        "",
        "        ArmyService.CreatePlayerArmy(player, hrp)",
        "    end)",
        "end",
        "",
        "Players.PlayerAdded:Connect(setup_player)",
        "for _, p in ipairs(Players:GetPlayers()) do",
        "    setup_player(p)",
        "end",
        "",
        "print(""[Server] NecroSnake boot complete"")"
    )
    Write-TextFileUtf8NoBom -Path (Join-Path $server_root "Main.server.lua") -Lines $main_server

    # Convert all Lua to UTF-8 no BOM
    $converted = Convert-LuaTreeToUtf8NoBom -Root $src_root
