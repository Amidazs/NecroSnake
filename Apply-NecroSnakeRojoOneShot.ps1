function Assert-FolderExists {
    <#
    .SYNOPSIS
    Ensures a folder exists.

    Args:
        path (string): Folder path.

    Returns:
        None
    #>
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path
    )

    if (-not (Test-Path -Path $Path -PathType Container)) {
        throw "Folder not found: $Path"
    }
}

function Ensure-Folder {
    <#
    .SYNOPSIS
    Creates a folder if it does not exist.

    Args:
        path (string): Folder path.

    Returns:
        string: Folder path.
    #>
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path
    )

    if (-not (Test-Path -Path $Path -PathType Container)) {
        New-Item -Path $Path -ItemType Directory | Out-Null
    }

    return $Path
}

function Write-TextFileUtf8NoBom {
    <#
    .SYNOPSIS
    Writes a UTF-8 (no BOM) text file, creating parent folders as needed.
    Accepts a string, string array, or anything enumerable.

    Args:
        path (string): Output file path.
        lines (object): Lines (string or string[]) to write.

    Returns:
        None
    #>
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path,

        [Parameter(Mandatory = $true)]
        [AllowNull()]
        [object]$Lines
    )

    $parent = Split-Path -Path $Path -Parent
    if ($parent -and -not (Test-Path -Path $parent -PathType Container)) {
        New-Item -Path $parent -ItemType Directory | Out-Null
    }

    $line_array = @()
    if ($null -eq $Lines) {
        $line_array = @()
    }
    elseif ($Lines -is [string]) {
        $line_array = @($Lines)
    }
    else {
        # Force enumeration into an array, even if it's a single item.
        $line_array = @($Lines)
    }

    $content = $line_array -join "`r`n"
    $utf8_no_bom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $content, $utf8_no_bom)

    Write-Host "✅ Wrote: $Path"
}


function Convert-LuaTreeToUtf8NoBom {
    <#
    .SYNOPSIS
    Converts all .lua files under a folder to UTF-8 without BOM.

    Args:
        root (string): Root folder.

    Returns:
        int: Count converted.
    #>
    param(
        [Parameter(Mandatory = $true)]
        [string]$Root
    )

    $count = 0
    $utf8_no_bom = New-Object System.Text.UTF8Encoding($false)

    Get-ChildItem -Path $Root -Recurse -File -Filter "*.lua" | ForEach-Object {
        $p = $_.FullName
        $raw = Get-Content -Path $p -Raw

        if ($raw.Length -gt 0 -and $raw[0] -eq [char]0xFEFF) {
            $raw = $raw.Substring(1)
        }

        [System.IO.File]::WriteAllText($p, $raw, $utf8_no_bom)
        $count += 1
    }

    return $count
}

